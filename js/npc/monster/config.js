    colonyHpMult: 3,      // 菌群血量倍率。★旧值 2 实测下来等于没有这个机制：一波三只合计 136 血，
                          //   玩家瞄着 Boss 打的时候顺带就把它们溅死了，"拦不拦"根本不构成决策。
                          //   3 = 一波 204 血 ≈ 中 build 1.6 秒集中火力，换掉的是下面那 18 点膜（=360 点原始伤害的活）
    colonyDist: [260, 380], // 回嵌的折返距离：被喷到这么远才掉头爬回来。刻意在初始射程 200 之外，必须主动走过去打
    colonyBurst: 420,       // 吐出瞬间的初速（像素/秒）：走到达 colonyDist 就掉头，所以飞行时长 = 折返距离 ÷ 420
    colonyBurstMax: 1400,   // ★初速段的时间上限（毫秒）：被海岸线卡住喷不出距离的菌群不能永远飘在外面
    filmPerEmbed: 6,      // 一只菌群嵌回去补多少膜，一波全回去 = 18 点（满膜的 18%）。
                          //   ★惩罚上限：回补速度 3×本行÷colonyCd 一旦高过玩家的侵蚀速度 R×filmBurn，
                          //   膜就永远钉在满值。这条分水岭在 R = 3×6÷7.6÷0.05 ≈ 47 点原始 DPS，
                          //   也就是"比中 build 还弱的玩家如果一只都不拦，会打很久"——是设计好的惩罚面，
                          //   但把本行调大之前先算这个数，否则中 build 也会一头撞上。
                          //   ★血 ×10 之后这条线咬得更狠：中 build 一只不拦实测 ≈1320 秒（见上面 hp 那段）
    // —— 三烟囱齐射：本场的硬威胁 ——
